#!/usr/bin/env python3
"""Encode the approved cover for the FM-1 display; no runtime image decoder."""
from pathlib import Path
from PIL import Image
root=Path(__file__).resolve().parents[1]
im=Image.open(root/'satie/art/SATIE-1-Erik-Evolved.png').convert('RGB').resize((240,240),Image.Resampling.LANCZOS)
im=im.quantize(colors=64,method=Image.Quantize.MEDIANCUT,dither=Image.Dither.NONE)
im.save(root/'satie/art/startup.png')
palette=im.getpalette()[:192]
words=[((palette[i]>>3)<<11)|((palette[i+1]>>2)<<5)|(palette[i+2]>>3) for i in range(0,len(palette),3)]
header='/* Generated by satie/gen_art.py from approved cover. See satie/art/CREDITS.txt. */\n'
header+='static const uint16_t SATIE_ART_PALETTE[64] = {'+','.join(str(x) for x in words)+'};\n'
data=im.tobytes();header+='static const uint8_t SATIE_ART[57600] = {\n'
header+='\n'.join(','.join(str(x) for x in data[i:i+120])+',' for i in range(0,len(data),120))+'\n};\n'
(root/'firmware/src/app/satie_art.h').write_text(header)
print('Startup cover encoded: 57,728 bytes in flash; reuses the existing screen canvas.')
