"""Reduce Satie piano scores to lead, bass and optional inner-voice data.

Quantise the original quarter-note timing to sixteenths, padding to 4/4 bars.
All editions split right/left staves into MIDI channels 0/1 respectively.
Only actual inner notes are stored; optional answers are generated in the DSP.
"""
import hashlib, json, math, re
from pathlib import Path
import mido
from catalog import SATIE
ROOT = Path(__file__).resolve().parents[1]

def reduce_score(source):
    path = ROOT/'satie/sources'/ (source['file']+'.mid')
    midi = mido.MidiFile(path)
    timed, time, end = [], 0, 0
    for message in mido.merge_tracks(midi.tracks):
        time += message.time
        if message.type in ('note_on','note_off'):
            timed.append((time,message)); end=time
    steps = max(16, math.ceil(end*4/midi.ticks_per_beat/16)*16)
    assert steps < 65536
    events=[[] for _ in range(steps)]
    for time,message in timed:
        step=round(time*4/midi.ticks_per_beat)
        if step < steps: events[step].append(message)
    active=set(); melody=[]; bass=[]; inner=[]
    for step,messages in enumerate(events):
        attacks=[]
        for message in messages:
            key=(message.channel,message.note)
            if message.type=='note_on' and message.velocity:
                active.add(key)
                if message.channel==0: attacks.append(message.note)
            else: active.discard(key)
        melody.append(max(attacks,default=0))
        bass.append(min((n for ch,n in active if ch==1),default=0) if step%4==0 else 0)
        pitches=sorted({n for ch,n in active})
        inner.append(pitches[-2] if len(pitches)>=3 else 0)
    assert sum(bool(n) for n in melody)>20
    if path.with_suffix('.json').exists():
        metadata=json.loads(path.with_suffix('.json').read_text())
        maintainer,license=metadata['maintainer'],metadata['license']
        assert license=='Public Domain'
    else:
        edition=path.with_suffix('.ly').read_text()
        maintainer=re.search(r'maintainer\s*=\s*"([^"]+)"',edition).group(1)
        if re.search(r'(?:license|copyright)\s*=\s*"Public Domain"',edition): license='Public Domain'
        elif 'licenses/by-sa/4.0' in edition: license='CC-BY-SA-4.0'
        else: raise ValueError(f'Unrecognised edition licence: {path}')
    return dict(source, file=path.name, sha256=hashlib.sha256(path.read_bytes()).hexdigest(), maintainer=maintainer, license=license, steps=steps, melody=melody,bass=bass,inner=inner)

def main():
    rows=[reduce_score(s) for s in SATIE]
    groups=list(dict.fromkeys(r['group'] for r in rows))
    notice='/* Generated by satie/generate.py. Attributed score data: see satie/SOURCES.txt. */\n'
    header=notice+f'''#pragma once
#include <stdint.h>
#define SATIE_SOURCES {len(rows)}
#define SATIE_COLLECTIONS {len(groups)}
typedef struct {{
    const char *title;
    uint8_t root, mode, tempo, slow, collection;
    uint16_t steps;
    const uint8_t *melody, *bass, *inner;
}} satie_source_t;
extern const satie_source_t SATIE_SOURCE[SATIE_SOURCES];
typedef struct {{
    const char *title;
    uint8_t first, count;
}} satie_collection_t;
extern const satie_collection_t SATIE_COLLECTION[SATIE_COLLECTIONS];
'''
    data=[notice]
    for index,row in enumerate(rows):
        for voice in ('melody','bass','inner'):
            data.append(f'static const uint8_t satie_{voice}_{index}[{row["steps"]}] = {{'+','.join(map(str,row[voice]))+'};')
    data+=['const satie_source_t SATIE_SOURCE[SATIE_SOURCES] = {']
    for i,r in enumerate(rows):
        data.append('    {"%s", %d, %d, %d, %d, %d, %d, satie_melody_%d, satie_bass_%d, satie_inner_%d},' % (r['title'],r['root'],r['mode'],r['tempo'],r['slow'],groups.index(r['group']),r['steps'],i,i,i))
    data+=['};','const satie_collection_t SATIE_COLLECTION[SATIE_COLLECTIONS] = {']
    for group in groups:
        ids=[i for i,r in enumerate(rows) if r['group']==group]
        data.append(f'    {{"{group.upper()}", {ids[0]}, {len(ids)}}},')
    data.append('};\n')
    (ROOT/'firmware/src/dsp/satie_data.h').write_text(header)
    (ROOT/'firmware/src/dsp/satie_data.inc').write_text('\n'.join(data))
    (ROOT/'satie/source-notes.json').write_text(json.dumps(rows,indent=2)+'\n')
    catalog=[dict(id=i,title=r['title'].title(),group=r['group'],composer=r['composer'],slow=r['slow'],tempo=r['tempo']) for i,r in enumerate(rows)]
    (ROOT/'satie/catalog.json').write_text(json.dumps(catalog,indent=2)+'\n')
    moods=list(reversed(json.loads((ROOT/'ockm/moods.json').read_text())))+[json.loads((ROOT/'satie'/name).read_text()) for name in ('orbit.json','blue-note.json','ghost.json')]
    moods[0]['parameters'].update(P_CM_DEC=68, P_CM_LVL=54, P_PAD=40, P_BASS=60)
    moods[1]['parameters'].update(P_CM_DEC=92, P_CM_LVL=50, P_PAD=56)
    header=['/* Generated by satie/generate.py. SPDX-License-Identifier: GPL-3.0-only */','#pragma once']
    for index,mood in enumerate(moods):
        header.append(f'static const int16_t SATIE_MOOD_{index}[][2] = {{')
        header.extend(f'    {{{name}, {value}}},' for name,value in mood['parameters'].items())
        header += ['    {-1, 0}','};']
    (ROOT/'firmware/src/app/satie_presets.h').write_text('\n'.join(header)+'\n')
    print(f'{len(rows)} complete score reductions; {sum(r["steps"]*3 for r in rows):,} bytes of note data.')
if __name__=='__main__':main()
